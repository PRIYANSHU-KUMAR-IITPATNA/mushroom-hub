export function farmerText(
  language: Language,
  key: FarmerTranslationKey,
  values?: Record<string, string | number>,
): string {
  const template = language === 'hi' ? hindi[key] : english[key]
  if (!values) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? ''),
  )
}
